STYLE_LABELS = {
    "business": "деловой",
    "neutral": "нейтральный",
    "friendly": "дружелюбный",
}

PLATFORM_INSTRUCTIONS = {
    "hh": (
        "Площадка — HH.ru. Сделай подробное описание с явными разделами "
        "«Задачи», «Требования» и «Условия» (используй именно эти заголовки). "
        "Внутри разделов используй списки, где это уместно."
    ),
    "telegram": (
        "Площадка — Telegram. Сделай компактный пост без громоздких заголовков: "
        "короткое вступление, затем основная информация (задачи, требования, условия) "
        "в сжатом виде, без лишних разделов. Текст должен легко читаться с телефона."
    ),
    "website": (
        "Площадка — сайт компании, раздел «Карьера». Сделай структурированный текст "
        "с понятными смысловыми блоками (о роли, задачи, требования, условия), "
        "подходящий для публикации на корпоративном сайте."
    ),
}


def build_prompt(data: dict) -> tuple[str, str]:
    style_key = data.get("text_style", "neutral")
    style_label = STYLE_LABELS.get(style_key, "нейтральный")

    platform_key = data.get("platform", "hh")
    platform_instruction = PLATFORM_INSTRUCTIONS.get(platform_key, PLATFORM_INSTRUCTIONS["hh"])

    system_prompt = (
        "Ты — опытный копирайтер по подготовке описаний вакансий. "
        "Пиши текст вакансии СТРОГО на основе сведений, предоставленных пользователем. "
        "Никогда не придумывай зарплату, льготы, график работы или другие условия, "
        "если они не были явно указаны. Если какая-то информация не предоставлена, "
        "просто не включай её в текст — не додумывай и не делай предположений. "
        f"Пиши в {style_label} стиле. Отвечай только готовым текстом вакансии, "
        "без пояснений и комментариев от себя."
    )

    fields = [
        ("Название роли", data.get("role", "")),
        ("Задачи", data.get("tasks", "")),
        ("Требования", data.get("requirements", "")),
        ("Условия работы", data.get("conditions", "")),
        ("Стиль компании", data.get("company_style", "")),
    ]
    fields_text = "\n".join(f"{label}: {value}" for label, value in fields if value)

    user_prompt = (
        f"{platform_instruction}\n\n"
        "Вот сведения о вакансии:\n"
        f"{fields_text}\n\n"
        "Сгенерируй готовый текст вакансии для публикации."
    )

    return system_prompt, user_prompt
